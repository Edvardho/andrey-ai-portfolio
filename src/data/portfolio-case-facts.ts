function unique(items: string[]): string[] {
  return [...new Set(items.map((item) => item.trim()).filter(Boolean))];
}

function factStatus(hasConfirmedFacts: boolean): SynthesisAnswerStatus {
  return hasConfirmedFacts ? 'grounded' : 'insufficient_facts';
}

function findMetricOutcome(pack: CaseFactPack): string | undefined {
  return pack.outcomes.find((outcome) => /%|₽|подписчик|секунд|диалог|вдвое|x2|активн/i.test(outcome));
}

